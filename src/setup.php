function setupPdo(array $input, bool $withDatabase): PDO
{
    $dsn = 'mysql:host=' . $input['db_host'] . ';port=' . $input['db_port'] . ';charset=utf8mb4';
    if ($withDatabase) {
        $dsn .= ';dbname=' . $input['db_name'];
    }

    return new PDO($dsn, $input['db_user'], $input['db_pass'], [
        PDO::ATTR_ERRMODE => PDO::ERRMODE_EXCEPTION,
        PDO::ATTR_DEFAULT_FETCH_MODE => PDO::FETCH_ASSOC,
        PDO::ATTR_EMULATE_PREPARES => false,
    ]);
}

function setupRunSql(PDO $pdo, string $file): void
{
    $sql = file_get_contents($file);
    if ($sql === false || trim($sql) === '') {
        throw new RuntimeException('SQL file is empty or unreadable: ' . basename($file));
    }

    $pdo->exec($sql);
}

function setupTableCount(PDO $pdo, string $database): int
{
    $statement = $pdo->prepare('SELECT COUNT(*) FROM information_schema.tables WHERE table_schema = ?');
    $statement->execute([$database]);
    return (int) $statement->fetchColumn();
}

function setupPrepareFolders(): array
{
    $results = [];
    foreach ([__DIR__, __DIR__ . '/usercontent', __DIR__ . '/usercontent/avatar'] as $directory) {
        if (!is_dir($directory)) {
            @mkdir($directory, 0775, true);
        }
        if (is_dir($directory)) {
            @chmod($directory, 0775);
        }
        $label = $directory === __DIR__ ? 'panel root' : str_replace(__DIR__, '', $directory);
        $results[] = [$label, is_dir($directory) && is_writable($directory)];
    }
    return $results;
}

function setupIniBytes(string $value): int
{
    $value = trim($value);
    $number = (int) $value;
    $unit = strtolower(substr($value, -1));
    if ($unit === 'g') {
        $number *= 1024;
    }
    if ($unit === 'g' || $unit === 'm') {
        $number *= 1024;
    }
    if (in_array($unit, ['g', 'm', 'k'], true)) {
        $number *= 1024;
    }
    return $number;
}

function setupCopyCoreTemplates(): void
{
    foreach (['Database', 'DiscordConfig'] as $file) {
        $source = __DIR__ . '/app/core/' . $file;
        $target = $source . '.php';
        if (!is_file($target)) {
            if (!is_file($source) || !copy($source, $target)) {
                throw new RuntimeException('Could not create app/core/' . $file . '.php');
            }
            @chmod($target, 0640);
        }
    }
}

function setupDetectedUrl(): string
{
    $secure = (!empty($_SERVER['HTTPS']) && strtolower((string) $_SERVER['HTTPS']) !== 'off')
        || strtolower((string) ($_SERVER['HTTP_X_FORWARDED_PROTO'] ?? '')) === 'https';
    $host = (string) ($_SERVER['HTTP_HOST'] ?? $_SERVER['SERVER_NAME'] ?? 'localhost');
    return ($secure ? 'https://' : 'http://') . $host;
}

function setupDetectedSubDir(): string
{
    $directory = str_replace('\\', '/', dirname((string) ($_SERVER['SCRIPT_NAME'] ?? '/setup.php')));
    return $directory === '/' || $directory === '.' ? '' : '/' . trim($directory, '/');
}

