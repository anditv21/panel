function setupEscape($value): string
{
    return htmlspecialchars((string) $value, ENT_QUOTES, 'UTF-8');
}

function setupEnv(string $key, string $default = ''): string
{
    return (string) Environment::get($key, $default);
}

function setupSqlFile(string $name): ?string
{
    $paths = [
        __DIR__ . '/' . $name,
        dirname(__DIR__) . '/' . $name,
        __DIR__ . '/install/' . $name,
    ];

    foreach ($paths as $path) {
        if (is_file($path) && is_readable($path)) {
            return $path;
        }
    }

    return null;
}

function setupWriteFile(string $path, string $contents): void
{
    $directory = dirname($path);
    if (!is_dir($directory) && !mkdir($directory, 0775, true) && !is_dir($directory)) {
        throw new RuntimeException('Could not create ' . $directory);
    }

    $temporary = $path . '.tmp-' . bin2hex(random_bytes(4));
    if (file_put_contents($temporary, $contents, LOCK_EX) === false) {
        throw new RuntimeException('Could not write ' . $path);
    }

    @chmod($temporary, 0640);
    if (!rename($temporary, $path)) {
        @unlink($temporary);
        throw new RuntimeException('Could not finish writing ' . $path);
    }
}

function setupLocalConfig(array $values): string
{
    return "<?php\n\n// Generated by setup.php. Environment variables can override these values.\nreturn "
        . var_export($values, true) . ";\n";
}

